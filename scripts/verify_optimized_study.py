#!/usr/bin/env python3
"""Rerun ALL frozen hypotheses with optimized code; keep both code identities."""

import argparse
from concurrent.futures import ProcessPoolExecutor, as_completed
import json
import multiprocessing as mp
from pathlib import Path
import shutil
import subprocess
import sys
import time

import pandas as pd

from benchmark_quant_workers import initialize_worker
from quant.data.snapshots import sha256_file, write_json
from quant.etl.restart import code_revision
from quant.longterm.pool_research import _run_asset


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("data_root", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--workers", type=int, default=4)
    parser.add_argument("--corrections", type=Path)
    args = parser.parse_args()
    if args.output.exists() or not 1 <= args.workers <= 6:
        raise ValueError("new directory and one to six workers required")
    original = json.loads((args.source / "registration.json").read_text())
    registered = dict(original)
    registered["code"] = code_revision()
    registered["performance_verification"] = {
        "source": str(args.source),
        "source_registration_sha256": sha256_file(args.source / "registration.json"),
        "original_code": original["code"],
        "original_experiments_unchanged": True,
        "workers": args.workers,
        "purpose": "equivalence_only_no_financial_selection",
        "prior_corrections_registration_sha256": (
            sha256_file(args.corrections / "registration.json") if args.corrections else None
        ),
    }
    coverage = json.loads((args.source / "coverage.json").read_text())
    args.output.mkdir(parents=True)
    write_json(args.output / "registration.json", registered)
    shutil.copytree(args.source / "inputs", args.output / "inputs")
    shutil.copy2(args.source / "coverage.json", args.output / "coverage.json")
    assets = {row["id"]: row for row in original["universe"]}
    jobs = [
        {
            "directory": str(args.output),
            "data_root": str(args.data_root),
            "asset": assets[row["asset"]],
            "evidence": row,
            "actions": (args.output / "inputs" / f"{row['asset']}_actions.parquet").exists(),
            "research_start": row["funding_start_after_shared_warmup"],
        }
        for row in coverage
        if row.get("status") != "blocked"
    ]
    start, outcomes = time.perf_counter(), []
    with ProcessPoolExecutor(
        max_workers=args.workers, mp_context=mp.get_context("spawn"), initializer=initialize_worker
    ) as pool:
        futures = {pool.submit(_run_asset, job): job["asset"]["id"] for job in jobs}
        for future in as_completed(futures):
            outcome = future.result()
            outcomes.append(outcome)
            print(json.dumps(outcome), flush=True)
    reference_files = json.loads((args.source / "payloads.json").read_text())
    changed, checked, missing = [], [], []
    # Per-asset outcomes include every financial payload and every stage feature.
    # Run-level prose/aggregation is not regenerated by this verification tool.
    for relative, expected in reference_files.items():
        parts = Path(relative).parts
        if len(parts) < 2 or parts[0] not in set(assets) | {"inputs"}:
            continue
        candidate = args.output / relative
        if not candidate.exists():
            missing.append(relative)
            continue
        original_hash = sha256_file(args.source / relative)
        actual = sha256_file(candidate)
        checked.append({"path": relative, "source": original_hash, "optimized": actual})
        if expected != original_hash or actual != original_hash:
            changed.append(relative)
    computed = sum(x["statuses"].get("computed", 0) for x in outcomes)
    expected_computed = json.loads((args.source / "summary.json").read_text())["statuses"][
        "computed"
    ]
    pd.DataFrame(checked).to_csv(args.output / "equivalence_files.csv", index=False)
    summary = {
        "wall_seconds": time.perf_counter() - start,
        "computed": computed,
        "checked_files": len(checked),
        "changed": changed,
        "missing": missing,
        "ok": not changed and not missing and computed == expected_computed,
        "source_identity_intentionally_different": True,
    }
    write_json(args.output / "performance_equivalence.json", summary)
    print(json.dumps(summary), flush=True)
    if args.corrections:
        subprocess.run(
            [
                sys.executable,
                str(Path(__file__).with_name("check_optimized_adjudicated.py")),
                str(args.source),
                str(args.output),
                str(args.corrections),
                str(args.output / "adjudicated_equivalence.json"),
            ],
            check=True,
        )
        return
    if not summary["ok"]:
        raise AssertionError("full-study optimized financial equivalence failed")


if __name__ == "__main__":
    main()
