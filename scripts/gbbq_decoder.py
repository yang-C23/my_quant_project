def _u32(buf: bytes, off: int) -> int:
    return struct.unpack_from("<I", buf, off)[0]


def _decrypt_block(keys: bytes, encrypted: bytes) -> bytes:
    """Decrypt one 8-byte block (Blowfish variant with fixed sub-keys)."""
    eax = _u32(keys, 0x44)
    A = struct.unpack_from("<I", encrypted, 0)[0]
    B = struct.unpack_from("<I", encrypted, 4)[0]

    num = eax ^ A
    numold = B

    j = 0x40
    while j >= 4:
        ebx = (num & 0xFF0000) >> 16
        eax = _u32(keys, ebx * 4 + 0x448)

        ebx = num >> 24
        eax = (eax + _u32(keys, ebx * 4 + 0x48)) & 0xFFFFFFFF

        ebx = (num & 0xFF00) >> 8
        eax ^= _u32(keys, ebx * 4 + 0x848)

        ebx = num & 0xFF
        eax = (eax + _u32(keys, ebx * 4 + 0xC48)) & 0xFFFFFFFF

        eax ^= _u32(keys, j)

        temp = num
        num = numold ^ eax
        numold = temp
        j -= 4

    numold ^= _u32(keys, 0)
    return struct.pack("<II", numold & 0xFFFFFFFF, num & 0xFFFFFFFF)


def decode_gbbq_file(filepath: str | Path) -> list[tuple]:
    """Decode an encrypted GBBQ file.

    Returns list of (category, symbol, date, c1, c2, c3, c4).
    """
    data = Path(filepath).read_bytes()
    if len(data) < 4:
        return []

    keys = _get_keys()
    count = struct.unpack_from("<I", data, 0)[0]

    results = []
    pos = 4

    for _ in range(count):
        if pos + 29 > len(data):
            break

        clear = bytearray(29)
        clear[0:8] = _decrypt_block(keys, data[pos:pos + 8])
        pos += 8
        clear[8:16] = _decrypt_block(keys, data[pos:pos + 8])
        pos += 8
        clear[16:24] = _decrypt_block(keys, data[pos:pos + 8])
        pos += 8
        clear[24:29] = data[pos:pos + 5]
        pos += 5

        code_bytes = clear[1:8]
        try:
            code_end = code_bytes.index(0)
        except ValueError:
            code_end = len(code_bytes)
        code = code_bytes[:code_end].decode("ascii", errors="ignore")

        symbol, ok = generate_symbol(code)
        if not ok:
            continue

        date_int = struct.unpack_from("<I", clear, 8)[0]
        dt = _parse_gbbq_date(date_int)
        if dt is None:
            continue

        category = clear[12]
        c1 = struct.unpack_from("<f", clear, 13)[0]
        c2 = struct.unpack_from("<f", clear, 17)[0]
        c3 = struct.unpack_from("<f", clear, 21)[0]
        c4 = struct.unpack_from("<f", clear, 25)[0]

        results.append((int(category), symbol, dt, float(c1), float(c2), float(c3), float(c4)))

    return results


def _parse_gbbq_date(d: int) -> date | None:
    if d == 0:
        return None
    y = d // 10000
    m = (d % 10000) // 100
    day = d % 100
    if m < 1 or m > 12 or day < 1 or day > 31:
        return None
    try:
        return date(y, m, day)
    except ValueError:
        return None


