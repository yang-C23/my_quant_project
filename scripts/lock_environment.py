#!/usr/bin/env python3
"""Capture the installed transitive project dependency closure without credentials."""

from __future__ import annotations

from importlib import metadata
from pathlib import Path
import sys

from packaging.markers import default_environment
from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

ROOT = Path(__file__).resolve().parents[1]


def main() -> None:
    """Write a rebuildable constraints file; local source patches are audited separately."""
    environment = default_environment()
    queue = [("my-quant", {"dev", "data"})]
    visited: dict[str, set[str]] = {}
    versions = {}
    while queue:
        name, extras = queue.pop()
        name = canonicalize_name(name)
        extras = extras | {""}
        if name in visited and extras.issubset(visited[name]):
            continue
        visited.setdefault(name, set()).update(extras)
        distribution = metadata.distribution(name)
        if name != "my-quant":
            versions[name] = distribution.version
        for text in distribution.requires or []:
            requirement = Requirement(text)
            if requirement.marker and not any(
                requirement.marker.evaluate({**environment, "extra": extra}) for extra in extras
            ):
                continue
            if requirement.url:
                raise ValueError(f"audit direct source dependency separately: {requirement.name}")
            queue.append((requirement.name, set(requirement.extras)))
    header = f"# Installed dependency closure; Python {sys.version_info.major}.{sys.version_info.minor}.\n# Generated by scripts/lock_environment.py; local source patches require separate audit.\n"
    (ROOT / "requirements-lock.txt").write_text(
        header + "\n".join(f"{n}=={v}" for n, v in sorted(versions.items())) + "\n"
    )
    print(f"Locked {len(versions)} installed dependencies")


if __name__ == "__main__":
    main()
